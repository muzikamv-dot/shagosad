package com.dsh.stepcounter;

/**
 * Описания предметов магазина и инвентаря.
 *
 * Раньше на вкладке «Инструменты» висело одно общее описание всех предметов,
 * и в инвентаре подписи были вписаны в карточки. Теперь описание у каждого своё
 * и открывается по тапу на иконку предмета — магазин от этого чище, а текст
 * не мешает выбирать.
 */
final class ItemInfo {

    private ItemInfo() { }

    static String title(int kind) {
        if (kind == ToolIcon.SHOVEL) return "Лопата";
        if (kind == ToolIcon.GARDENER) return "Садовник";
        return "Тяпка";
    }

    /** Что делает предмет и сколько стоит. */
    static String text(int kind) {
        if (kind == ToolIcon.SHOVEL) {
            return "Перекапывает землю, если цветок засох после трёх пропусков подряд.\n\n"
                    + "Засохнуть можно, если три дня подряд не выполнять норму шагов. "
                    + "Лопата возвращает грядку: цветок осыпался, но землю можно перекопать "
                    + "и посадить то же семя заново.\n\n"
                    + "Одна лопата — одно перекапывание. Цена: "
                    + Shop.money(GameState.SHOVEL_PRICE) + " очков.";
        }
        if (kind == ToolIcon.GARDENER) {
            return "Заморозка грядки на сегодня.\n\n"
                    + "Купленный садовник лежит в инвентаре: открывай «Инвентарь» и применяй его "
                    + "кнопкой «Применить на грядку» — из магазина он на грядку не ставится.\n\n"
                    + "Применил — и до полуночи грядка во льду: с цветком нельзя ничего, "
                    + "ни полить, ни собрать. Зато и штрафа за этот день не будет, а если на "
                    + "цветке уже был сорняк, второй не прибавится.\n\n"
                    + "На следующий день — бонус: шаги считаются вдвое для закрытия дневной нормы. "
                    + "Цифры шагов, расстояние, скорость и вода остаются настоящими, "
                    + "бонус только помогает закрыть день без штрафа.\n\n"
                    + "Один садовник — один такой день. Покупать можно сколько угодно. "
                    + "Цена: " + Shop.money(GameState.GARDENER_PRICE) + " очков.";
        }
        return "Срезает один сорняк.\n\n"
                + "Сорняки появляются, если не выполнить дневную норму шагов: сначала один, "
                + "потом второй. Сорняк замедляет накопление воды вдвое, а цветок с ним "
                + "растёт медленнее.\n\n"
                + "Одна тяпка — один сорняк. Цена: "
                + Shop.money(GameState.HOE_PRICE) + " очков.";
    }

    /** Окно с описанием инструмента. */
    static void show(android.app.Activity a, int kind) {
        show(a, title(kind), text(kind));
    }

    /** Окно с произвольным заголовком и текстом (редкие семечки и прочее). */
    static void show(android.app.Activity a, String title, String text) {
        if (a == null || a.isFinishing()) return;
        new android.app.AlertDialog.Builder(a)
                .setTitle(title)
                .setMessage(text)
                .setPositiveButton("Понятно", null)
                .show();
    }
}
